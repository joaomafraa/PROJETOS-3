CREATE TABLE servicos_contratados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    tipo VARCHAR(20) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    detalhe VARCHAR(300),
    situacao VARCHAR(20) NOT NULL,
    inicio DATE NOT NULL,
    fim DATE,
    demonstracao BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT ck_servico_tipo CHECK (tipo IN ('PLANO', 'SERVICO')),
    CONSTRAINT ck_servico_situacao CHECK (situacao IN ('ATIVO', 'SUSPENSO', 'ENCERRADO')),
    CONSTRAINT ck_servico_periodo CHECK (fim IS NULL OR fim >= inicio),
    CONSTRAINT ck_servico_demonstracao CHECK (demonstracao = TRUE)
);

CREATE INDEX idx_servicos_contratados_cliente ON servicos_contratados (empresa_id, cliente_id);
