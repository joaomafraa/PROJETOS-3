-- HU02.2: origem das respostas automaticas.
-- Guarda uma copia do titulo, da versao e do trecho usados, para que a origem
-- continue identificavel mesmo se o documento for desativado ou atualizado.
-- RECUPERADA: trecho entregue a IA. CITADA: trecho que a resposta referenciou.
CREATE TABLE fontes_resposta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresas(id),
    conversa_id BIGINT NOT NULL REFERENCES conversas(id),
    mensagem_id BIGINT NOT NULL,
    uso VARCHAR(20) NOT NULL,
    numero INTEGER,
    ordem INTEGER NOT NULL,
    documento_id BIGINT NOT NULL,
    documento_versao VARCHAR(64) NOT NULL,
    documento_titulo VARCHAR(200) NOT NULL,
    trecho_id VARCHAR(100) NOT NULL,
    localizacao VARCHAR(200),
    excerto TEXT NOT NULL,
    registrada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_fontes_mensagem FOREIGN KEY (conversa_id, mensagem_id) REFERENCES mensagens (conversa_id, id),
    CONSTRAINT ck_fontes_uso CHECK (uso IN ('RECUPERADA', 'CITADA')),
    CONSTRAINT ck_fontes_numero CHECK (
        (uso = 'CITADA' AND numero IS NOT NULL AND numero > 0)
        OR (uso = 'RECUPERADA' AND numero IS NULL)
    ),
    CONSTRAINT ck_fontes_ordem CHECK (ordem >= 0),
    CONSTRAINT uk_fontes_trecho UNIQUE (conversa_id, mensagem_id, uso, documento_id, documento_versao, trecho_id)
);

CREATE INDEX idx_fontes_resposta_conversa ON fontes_resposta (empresa_id, conversa_id, mensagem_id, uso, ordem);
