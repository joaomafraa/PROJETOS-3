CREATE TABLE mensagens (
    codigo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id BIGINT NOT NULL CHECK (id > 0),
    conversa_id BIGINT NOT NULL REFERENCES conversas(id),
    conteudo TEXT NOT NULL,
    data_envio TIMESTAMP WITH TIME ZONE NOT NULL,
    remetente VARCHAR(20) NOT NULL,
    atendente_id BIGINT REFERENCES atendentes(id),
    ordem INTEGER NOT NULL CHECK (ordem >= 0),
    CONSTRAINT uk_mensagem_conversa_id UNIQUE (conversa_id, id),
    CONSTRAINT ck_mensagem_autor CHECK (
        (remetente = 'ATENDENTE' AND atendente_id IS NOT NULL)
        OR (remetente IN ('CLIENTE', 'CHATBOT') AND atendente_id IS NULL)
    )
);

CREATE INDEX idx_mensagens_historico ON mensagens (conversa_id, ordem);
